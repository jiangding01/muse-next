/**
 * TAB（吉他六线谱）专属几何（M2 方案 §3.3，T6.1 追加；abstract unit，D6，**不是像素**）。
 *
 * 除 `stringCount` 外，**每一项都是产品决定，不是格式事实**：spec §26 只规定了
 * 「弦号 a..f → 1..6」「品位是数字或 `x`」这类语义，从未规定弦间距、字号、留白等
 * 任何排版数值。`stringCount: 6` 是格式事实（spec §26.2：六线，a..f → 1..6）。
 *
 * 与 `JIANPU_METRICS` **平行且独立**：TAB 不复用简谱的任何几何常量，两种记谱的
 * 纵向基准（数字基线 vs 六条弦线）本质不同，共用常量只会让一处调整误伤另一处。
 */
export const TAB_METRICS = {
  /** 弦数：六线谱固定 6 弦（**格式事实**，spec §26.2：a..f → 1..6）。 */
  stringCount: 6,
  /** 相邻两条弦线的垂直间距（产品决定，不是格式事实）。 */
  lineGap: 8,
  /** 第 1 弦（最上一条）相对 system box 顶边的垂直偏移；其上方留给和弦符号行（产品决定）。 */
  staffTopOffset: 16,
  /** 品位数字的度量字号（产品决定）。 */
  fretFontSize: 10,
  /** 倚音品位的小字号（spec §21：倚音不占时值；字号大小本身是产品决定）。 */
  graceFontSize: 7,
  /**
   * 字形视觉中线到文本基线的比例（产品决定）：品位数字画在弦线**上**，要以线为中心
   * 视觉居中，故基线 = 线 y + fontSize × 本比例。写成比例而不是固定偏移，倚音小字号
   * 才能跟着缩放。
   */
  fretBaselineRatio: 0.35,
  /** 品位数字左右留白：`tabSlotWidths.ts` 的列宽下界用它（产品决定）。 */
  fretPaddingX: 3,
  /** 品位数字白底矩形相对字形 bbox 的四周外扩量——它要遮住穿过数字的弦线（产品决定）。 */
  fretBackdropPadding: 2,
  /**
   * 一行谱（system）的整体高度（产品决定）。T6.2 追加时值装饰后从 72 调到 92，
   * 推导：第 6 弦相对 system box 顶边 = `staffTopOffset(16) + 5×lineGap(8) = 56`；
   * 之下要放得下「符干 + 两条减时线」（覆盖到十六分音符，`beams = 2`）——
   * `stemOffsetY(4) + stemLength(16) + beamFirstOffset(4) + (2-1)×beamGap(4) = 28`；
   * 56 + 28 = 84，再留 `decorationBottomMargin`（8）的下方余量 = 92。延音短横线
   * （`base ≥ 1`）只在 `stemOffsetY` 处画一行，远浅于这个上限，不构成新的约束。
   *
   * **`decomposeDuration` 允许 `beams` 到 8**（`base = 1/1024`）：更细的时值（三十二
   * 分及更细）纵向会超出这个上限，这里**不再继续加大常量**去覆盖极端情形（那会让
   * 绝大多数行谱平白多出一截空白）——改由 `layoutTab.ts` 按每行谱实际出现的最深
   * 装饰（`tabDurationGlyphs.ts` 的 `requiredSystemDepth`）逐行谱补高
   * （`layout/systems.ts` 的 `restackSystems`，与 `jianpu/layoutJianpu.ts` 按歌词
   * 行数补高同一套两趟布局手法）。`systemHeight` 因此是「常规情形（到十六分音符）
   * 不必补高的基准值」，不是硬上限。
   */
  systemHeight: 92,
  /**
   * 一行谱下方为时值装饰预留的余量（产品决定）：`systemHeight` 与
   * `requiredSystemDepth`（按实际装饰深度回填行高）共用同一个余量常量，两处
   * 「装饰画完之后还留多少空白才不贴下一行」的产品判断没有理由不一致。
   */
  decorationBottomMargin: 8,
  /** 相邻两行谱之间的垂直间隙（产品决定）。 */
  systemGap: 16,
  /** 头部标签区高度；system 从它下方开始排布（产品决定）。 */
  headerHeight: 20,
  /** 和弦符号（`"C"`，spec §25）的度量字号（产品决定）。 */
  chordSymbolFontSize: 10,
  /** 和弦符号基线相对第 1 弦线的垂直偏移（负值 = 画在谱上方那条预留行里，产品决定）。 */
  chordSymbolOffsetY: -6,
  /** 小节线相对第 1 / 第 6 弦的上下超出量；取 0 = 恰好贯穿六线（产品决定）。 */
  barlineOverhang: 0,
  /** 复合小节线（`|]` / `|:` / `:|`）两根竖线之间的水平间距（产品决定）。 */
  barlineCompositeGap: 3,
  /** 反复点半径（产品决定）。 */
  repeatDotRadius: 1.5,
  /** 反复点相对小节线的水平偏移（产品决定）。 */
  repeatDotOffsetX: 4,
  /** 两个反复点相对六线纵向中心的垂直偏移量（一上一下，产品决定）。 */
  repeatDotOffsetY: 8,
  /** 休止符文本的度量字号（spec §26.9：TAB 声部里的 `z` 与 pitch 模式同形）（产品决定）。 */
  restFontSize: 10,
  /** 未知 / 范围外 / 装饰占位文本的度量字号（产品决定）。 */
  unknownFontSize: 10,
  /** 倚音品位相对主音列的水平偏移量（`after` 为真时取正、否则取负）（产品决定）。 */
  graceOffsetX: 9,

  // -------------------------------------------------------------------------
  // 时值装饰（T6.2 追加）。spec §26 从未规定 TAB 时值的画法（符干长度、减时线
  // 间距……）——以下**每一项都是产品决定，不是格式事实**，参照通行吉他六线谱把
  // 装饰画在第 6 弦下方的最小形态给出一组自洽数值。
  // -------------------------------------------------------------------------

  /** 符干顶端相对第 6 弦线的垂直距离（留一点呼吸空间，不紧贴弦线）（产品决定）。 */
  stemOffsetY: 4,
  /** 四分及更短时值的符干长度（产品决定）。 */
  stemLength: 16,
  /**
   * 二分音符的短符干长度：取 `stemLength` 的一半，视觉上与四分及更短时值的符干
   * 明确区分开，但仍看得出「这里有一根符干」（产品决定）。
   */
  halfStemLength: 8,
  /**
   * 第一条减时线相对符干底端的垂直偏移。减时线从符干底端**向下、向右**等距排列
   * （每条从符干的 x 起向右画 `beamLength`，逐条向下错开 `beamGap`）——选择向下
   * 是因为符干本身已经向下伸出，减时线顺着同一方向延续，不会往回穿回弦线区域
   * （产品决定）。
   */
  beamFirstOffset: 4,
  /** 相邻两条减时线的垂直间距（产品决定）。 */
  beamGap: 4,
  /** 单条减时线的水平长度（产品决定）。 */
  beamLength: 8,
  /** 附点半径（产品决定）。 */
  augmentationDotRadius: 1.5,
  /**
   * 附点相对符干（有符干时）或延音短横线末尾（无符干、`base ≥ 1` 时）的水平偏移
   * （产品决定）；两种情形复用同一个偏移量，没有另立标准的理由。
   */
  augmentationDotOffsetX: 4,
  /** 相邻两个附点的水平间距（产品决定）。 */
  augmentationDotGap: 4,
  /** 单条延音短横线（`base ≥ 1` 时表示延长）的水平长度（产品决定）。 */
  dashLength: 10,
  /** 相邻两条延音短横线的水平间距（产品决定）。 */
  dashGap: 6,
  /** 第一条延音短横线相对事件列左边界（`x`）的水平偏移（产品决定）。 */
  dashFirstOffset: 0,
} as const;
